// Embed an .xlsx report template as a base64 TypeScript constant.
// The template's author metadata (docProps/core.xml creator / lastModifiedBy) is
// replaced with "OdoLens" and the scrubbed bytes are written back to the source
// template, so no personal name is committed or copied into consolidated files.
// Usage: node scripts/embed-template.mjs <template.xlsx> <output.ts>
import { readFileSync, writeFileSync } from 'node:fs'
import { basename } from 'node:path'
import JSZip from 'jszip'

const [input, output] = process.argv.slice(2)
if (!input || !output) {
  console.error('usage: node scripts/embed-template.mjs <template.xlsx> <output.ts>')
  process.exit(2)
}

const zip = await JSZip.loadAsync(readFileSync(input))
const core = zip.file('docProps/core.xml')
if (core) {
  const xml = await core.async('text')
  zip.file(
    'docProps/core.xml',
    xml
      .replace(/<dc:creator>[^<]*<\/dc:creator>/, '<dc:creator>OdoLens</dc:creator>')
      .replace(/<cp:lastModifiedBy>[^<]*<\/cp:lastModifiedBy>/, '<cp:lastModifiedBy>OdoLens</cp:lastModifiedBy>'),
  )
}
const bytes = await zip.generateAsync({ type: 'nodebuffer', compression: 'DEFLATE', compressionOptions: { level: 6 } })
writeFileSync(input, bytes)

const base64 = bytes.toString('base64')
writeFileSync(
  output,
  `// Auto-generated by scripts/embed-template.mjs — do not edit manually\n` +
    `// Source: ${basename(input)}\n` +
    `export const TEMPLATE_V2026_BASE64 = ${JSON.stringify(base64)}\n`,
)
console.log(`wrote ${output} (${base64.length} base64 chars); scrubbed ${input}`)
